export type TranslationKey = keyof typeof messages.en;
export type TranslationValues = Record<string, string | number>;

export function isLocale(value: string | undefined): value is Locale {
  return value === "en" || value === "es";
}

export function translate(locale: Locale, key: TranslationKey, values: TranslationValues = {}): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export function statusTranslationKey(status: "WISHLIST" | "PLANNED" | "VISITED"): TranslationKey {
  return `status.${status.toLowerCase()}` as TranslationKey;
}

export function categoryTranslationKey(category: string): TranslationKey {
  const keys: Record<string, TranslationKey> = {
    COASTER: "category.rollerCoaster",
    ROLLER_COASTER: "category.rollerCoaster",
    WATER: "category.waterRide",
    WATER_RIDE: "category.waterRide",
    DARK_RIDE: "category.darkRide",
    SHOW: "category.flatRide",
    FLAT_RIDE: "category.flatRide",
    UNKNOWN: "category.unknown",
  };
  return keys[category] ?? "category.flatRide";
}

export function preferredRowLabel(locale: Locale, value: string | null | undefined): string {
  if (!value) return translate(locale, "dashboard.noPreferredRow");
  const keys: Record<string, TranslationKey> = {
    "Front Row": "visits.frontRow",
    "Back Row": "visits.backRow",
    Middle: "visits.middleRow",
    Custom: "visits.customRow",
  };
  return keys[value] ? translate(locale, keys[value]) : value;
}

export function translateError(locale: Locale, error: unknown, fallback: TranslationKey): string {
  const message = error instanceof Error ? error.message : "";
  if (message === "Unauthorized") return translate(locale, "error.unauthorized");
  if (message === "Authentication is not configured") return translate(locale, "error.authNotConfigured");
  if (message === "Invalid credentials") return translate(locale, "error.invalidCredentials");
  if (message === "Invalid backup") return translate(locale, "error.invalidBackup");
  if (message === "Invalid timestamp") return translate(locale, "error.invalidTimestamp");
  if (message === "External park was not found") return translate(locale, "error.externalNotFound");
  const requestFailure = message.match(/^Queue-Times request failed with status (\d+)$/);
  if (requestFailure) return translate(locale, "error.requestFailed", { status: requestFailure[1] });
  return message || translate(locale, fallback);
}
